def normalize_body(text):
    return ''.join(c for c in text if c.isalnum())


def publish(group):
    p = Pipeline()
    source_path = p.root / SOURCE
    assert hashlib.sha256(source_path.read_bytes()).hexdigest() == SOURCE_SHA, 'Source changed'
    original = read(source_path)
    # Detect any accidental edit of official files or already approved entries.
    protected = {path: path.read_bytes() for path in (p.root / 'data').rglob('*.json')}
    _, _, initial_dictionary, _ = p.inspect()
    for ch, entry in initial_dictionary.items():
        if entry.get('approved'):
            for path in (p.work / 'dictionary' / (ch + '.json'),
                         p.work / 'reviews/dictionary' / (ch + '.json')):
                if path.exists():
                    protected[path] = path.read_bytes()
    eligible = []
    for number, ci, pi, translation, notes, assessment, choice in GROUPS[group]:
        pid = 'guwen-' + str(number).zfill(3)
        if pid not in p.pending:
            print('SKIP not selected/pending', pid)
            continue
        poem = p.poems[pid]
        assert poem['author'] == '孔子及其弟子' and poem['category'] == '古文'
        assert normalize_body(poem['content']) == normalize_body(original[ci]['paragraphs'][pi]), pid
        assert 3 <= len(notes) <= 8 and all(term in poem['content'] for term, _ in notes), pid
        ih = p.input_hash(poem)
        patch = dict(id=pid, tags=['说理', '哲理'], translation=translation,
                     notes=[dict(term=t, meaning=m) for t, m in notes])
        validate_patch(patch, poem, p.tags['古文'])
        url = V1 if ci < 2 else V2
        refs = [dict(kind='public_domain_commentary', author='朱熹', title='论语集注',
                     url=url, revisionId=REVISIONS[url], chapter=original[ci]['chapter'],
                     locus=poem['content'][:40])]
        if number in (91, 92, 94, 98, 100):
            refs.append(dict(kind='public_domain_commentary_crosscheck',
                             title='论语注疏（四库全书本）卷三', url=OLD3, revisionId='524865',
                             locus=poem['content'][:40]))
        if number == 98:
            refs.append(dict(kind='pronunciation_crosscheck', title='重编国语辞典·告朔',
                             url='https://dict.revised.moe.edu.tw/dictView.jsp?ID=71411&la=1&powerMode=0'))
        origin = dict(file=SOURCE, sha256=SOURCE_SHA, jsonPointer=f'/{ci}/paragraphs/{pi}',
                      chapter=original[ci]['chapter'], paragraphIndex=pi, hasTranslation=False)
        reference_path = p.work / 'references' / f'{pid}--{ih}--independent-zhu.json'
        write_once(reference_path, dict(id=pid, inputHash=ih, normalizedTextMatch=True,
                   originalSource=origin, references=refs,
                   policy='经逐章核读原文与公版朱注后独立整理，匹配只验证文本，不产生语义批准；未复制现代译注。'))
        write_once(p.result_path(poem), patch)
        if choice:
            write_once(p.work / 'reviewissues' / f'{pid}--{ih}--reading-choice.json',
                       dict(id=pid, inputHash=ih, resultHash=digest(patch),
                            decision='documented_reading_choice', blocksAssembly=False,
                            references=refs, unresolvedQuestions=[], **choice))
        write_once(p.work / 'reviews' / f'{pid}--{ih}.json',
                   dict(decision='approved', reviewer='Codex independent classical prose editorial review',
                        inputHash=ih, resultHash=digest(patch), assessment=assessment,
                        referenceFile=p.relative(reference_path), references=refs,
                        originalSource=origin, checkedNotes=len(notes),
                        editorialPolicy='逐章独立核对全文、词注及语境后批准；古注读音与今音分别对待；格式校验只作发布完整性检查。'))
        eligible.append(pid)
        print('APPROVED', pid, len(notes))
    # Re-read global candidates immediately before publication; never select first.
    p = Pipeline()
    _, _, dictionary, _ = p.inspect()
    needed = set().union(*(characters(p.poems[pid]['content']) for pid in eligible)) - set(p.dictionary)
    created = []
    for ch in sorted(needed):
        if dictionary.get(ch, {}).get('approved'):
            continue
        assert ch in DEFINITIONS, ('Unreviewed missing definition', ch)
        meanings, ancient, url, assessment = DEFINITIONS[ch]
        definition = normalize_definition(dict(meanings=meanings, ancient=ancient))
        candidates = dictionary.get(ch, {}).get('candidates', [])
        write_once(p.work / 'dictionary' / f'{ch}.json', definition)
        write_once(p.work / 'reviews/dictionary' / f'{ch}.json',
                   dict(decision='approved', reviewer='Codex dictionary editorial review',
                        definitionHash=digest(definition),
                        contextIds=[pid for pid in eligible if ch in p.poems[pid]['content']],
                        references=[url], reviewedCandidateHashes=[c['definitionHash'] for c in candidates],
                        candidateSources=[s for c in candidates for s in c['sources']],
                        editorialNote=assessment))
        created.append(ch)
    for path, before in protected.items():
        assert path.read_bytes() == before, ('Protected file changed', str(path))
    fresh = Pipeline()
    _, drafts, dictionary, _ = fresh.inspect()
    for pid in eligible:
        assert drafts[pid]['approved'], pid
        for ch in characters(fresh.poems[pid]['content']) - set(fresh.dictionary):
            assert dictionary[ch]['approved'], (pid, ch)
    print('GROUP', group, 'approved', len(eligible), 'new canonical', ''.join(created))


if __name__ == '__main__':
    publish(int(sys.argv[1]))
